#!/usr/bin/env node
/**
 * Build `lib/client.js` for dsh-compact-manager.
 *
 * The browser half ships as one file: `window.__ModuleLoader__.load({ factory })`
 * registers exactly one module per call, so the saviour ring/meter/satellite
 * primitives are inlined rather than imported.
 *
 * Output order:
 *   1. module wrapper, with react / react-dom supplied by the loader
 *   2. vendored dsh-compact-saviour 0.2.8 primitives (MIT) + its stylesheet
 *   3. stylesheet from tools/style.js
 *   4. the merged footer, settings page and slot registration (tools/client-app.js)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const read = (path) => readFileSync(path, "utf8");

const primitives = read(join(root, "lib/client-vendor/saviour-ui.js"))
  // Drop the extraction banner: the build output carries its own provenance note.
  .replace(/^\/\*\*[\s\S]*?\*\/\n\n/, "")
  // The wrapper below already declares these; the vendored chunk kept its own
  // copies from inside the original factory. Aliases keep the rest of the chunk
  // (which refers to `react`, `react_dom`, `react_jsx_runtime`) working.
  .replace(/^\t\tlet react = require\("react"\);\n/m, "\t\tconst react = React;\n")
  .replace(/^\t\tlet react_dom = require\("react-dom"\);\n/m, "\t\tconst react_dom = ReactDOM;\n")
  .replace(/^\t\tlet react_jsx_runtime = require\("react\/jsx-runtime"\);\n/m, "\t\tconst react_jsx_runtime = jsxRuntime;\n");

const saviourCss = read(join(root, "lib/client-vendor/saviour.css.js"))
  .replace(/^\/\*\*[\s\S]*?\*\/\n/, "")
  .replace(/^export const saviourCss = /, "")
  .replace(/;\n$/, "");

/**
 * Dead rules from the vendored stylesheet.
 *
 * The vendored copy stays faithful to dsh-compact-saviour — tools/extract-vendor.mjs
 * cuts it out by line number, so a hand edit there would be lost on the next
 * upgrade. The rules that only served the removed long-press gesture and the
 * removed hint line are therefore dropped here instead: the hold ring, its charge
 * animation, and `.dsh-cs-hint`. Each pattern asserts its own presence, so an
 * upstream restyle fails the build loudly rather than silently shipping dead CSS.
 */
const DEAD_CSS = [
  ".dsh-cs-hint{text-align:center;color:var(--dsw-alias-label-tertiary,#8a9099);font-size:10px;line-height:1.5}",
  ".dsh-cs-hold{opacity:0;transform:rotate(-90deg)}",
  ".dsh-cs-hold circle{fill:none;stroke:currentColor;stroke-width:1.8px;stroke-linecap:round;stroke-dasharray:1;stroke-dashoffset:1px}",
  "[data-cs-holding] .dsh-cs-hold{opacity:1}",
  "[data-cs-holding] .dsh-cs-hold circle{animation:.65s linear forwards dsh-cs-charge}",
  "@keyframes dsh-cs-charge{to{stroke-dashoffset:0}}",
  "[data-cs-holding] .dsh-cs-hold circle{stroke-dashoffset:.25px;animation:none}"
];
let trimmedCss = saviourCss;
for (const rule of DEAD_CSS) {
  if (!trimmedCss.includes(rule)) throw new Error(`dead CSS rule not found (upstream changed): ${rule.slice(0, 60)}`);
  trimmedCss = trimmedCss.replace(rule, "");
}
if (trimmedCss.includes("data-cs-holding")) throw new Error("a hold-ring rule survived the strip");

const ledgerCss = read(join(here, "style.js"))
  .replace(/^\/\*\*[\s\S]*?\*\/\n\n/, "")
  .replace(/^export const LEDGER_CSS = /, "")
  .replace(/;\n$/, "");

const app = read(join(here, "client-app.js"));

const out = `/**
 * dsh-compact-manager — browser half.
 *
 * The ring control, meter bridge and satellite animation are vendored from
 * dsh-compact-saviour 0.2.8 (MIT); the fold algorithm comes from
 * dsh-ledger-compact 0.13.4. Everything else is this plugin's own. See NOTICE.
 *
 * Generated by tools/build-client.mjs — edit tools/client-app.js and tools/style.js,
 * then run \`node tools/build-client.mjs\`.
 */
window.__ModuleLoader__.load({
\tid: "dsh-compact-manager",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\tlet React = require("react");
\t\tlet ReactDOM = require("react-dom");
\t\tlet jsxRuntime = require("react/jsx-runtime");

${nest(primitives, 2)}

\t\t//#region styles
\t\tconst CSS = ${trimmedCss} + ${ledgerCss};
\t\t//#endregion

${nest(app, 2)}

\t\treturn module.exports;
\t}
});
`;

writeFileSync(join(root, "lib/client.js"), out);
console.log(`lib/client.js: ${out.split("\n").length} lines, ${Buffer.byteLength(out)} bytes`);

/** Nest a chunk so the bundle stays readable. */
function nest(text, levels) {
  const pad = "\t".repeat(levels);
  return text
    .split("\n")
    .map((line) => (line.trim() ? pad + line : line))
    .join("\n");
}
